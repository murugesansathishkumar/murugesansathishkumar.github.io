/* Appends the authors line, wrapping "M. Sathishkumar" (and the
   corresponding-author form "M. Sathishkumar*") in <strong>. */
function appendAuthors(element, text) {
  const pattern = /(M\.\s*Sathishkumar\*?)/g;
  text.split(pattern).forEach(part => {
    if (!part) return;
    if (/^M\.\s*Sathishkumar\*?$/.test(part)) {
      const strong = document.createElement("strong");
      strong.textContent = part;
      element.appendChild(strong);
    } else {
      element.appendChild(document.createTextNode(part));
    }
  });
}

function displayPublications() {
  const section = document.getElementById("publications");
  const groups = [
    ["journals", "Journals", "Journal Publications"],
    ["conferences", "Conference Proceedings", "Refereed / International Conference Proceedings"],
    ["presentations", "Abstract / Presentation at Conference", "Abstract / Presentation at Conference"]
  ];
  const navigation = document.createElement("div");
  navigation.className = "subnav";
  section.appendChild(navigation);
  for (const [key, label, heading] of groups) {
    const link = document.createElement("a");
    link.href = "#publications/" + key;
    link.dataset.sub = key;
    link.textContent = label;
    navigation.appendChild(link);
    const panel = document.createElement("div");
    panel.className = "sub-panel";
    panel.dataset.sub = key;
    const card = document.createElement("div");
    card.className = "card";
    const title = document.createElement("h2");
    title.textContent = heading;
    card.appendChild(title);
    panel.appendChild(card);
    section.appendChild(panel);
    const list = key === "talks" ? document.createElement("div") : card;
    if (key === "talks") { list.className = "timeline"; card.appendChild(list); }
    for (const record of publications[key]) {
      if (key === "talks") {
        const item = document.createElement("div"); item.className = "item";
        const name = document.createElement("strong"); name.textContent = record.title;
        const detail = document.createElement("span"); detail.textContent = record.detail;
        item.append(name, detail); list.appendChild(item);
        continue;
      }
      const article = document.createElement("article");
      article.className = "publication" + (key === "journals" ? "" : " compact");
      const year = document.createElement("div");
      year.className = "pub-year"; year.textContent = record.year;
      const details = document.createElement("div");
      for (const [tag, field, className] of [
        ["h4", "title", ""], ["p", "authors", "authors"],
        ["p", "venue", "venue"], ["span", "badge", "badge"]
      ]) {
       if (!record[field]) continue;
        const element = document.createElement(tag);
        if (className) element.className = className;
        if (field === "title" && record.link) {
          const a = document.createElement("a");
          a.href = record.link;
          a.target = "_blank";
          a.rel = "noopener";
          a.textContent = record[field];
          element.appendChild(a);
        } else {
          element.textContent = record[field];
        }
        details.appendChild(element);
      }
      article.append(year, details); list.appendChild(article);
    }
  }
}
displayPublications();
